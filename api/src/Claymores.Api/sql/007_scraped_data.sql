-- Give every remaining team a unique slug.
DO $$
DECLARE
    team record;
    base text;
    candidate text;
    n integer;
BEGIN
    FOR team IN SELECT name FROM teams WHERE slug IS NULL ORDER BY name LOOP
        base := COALESCE(NULLIF(btrim(regexp_replace(lower(team.name), '[^a-z0-9]+', '-', 'g'), '-'), ''), 'team');
        candidate := base;
        n := 1;
        WHILE EXISTS (SELECT 1 FROM teams WHERE slug = candidate) LOOP
            n := n + 1;
            candidate := base || '-' || n;
        END LOOP;
        UPDATE teams SET slug = candidate WHERE name = team.name;
    END LOOP;
END $$;

-- ── Fixtures ───────────────────────────────────────────────────────────────
-- Rows from --import-fixtures keep source = 'sanity' and are served by the public
-- endpoints. The scraper writes source = 'scraper' rows in shadow mode until cutover.
-- For scraper rows: home_team/away_team hold the resolved team name, *_raw hold the
-- name as displayed ("Claymores" for our side, rugbyfl.com's spelling for the opponent).
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS source text NOT NULL DEFAULT 'sanity';
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS home_team_id bigint REFERENCES teams (id);
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS away_team_id bigint REFERENCES teams (id);
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS home_team_raw text;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS away_team_raw text;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS status text;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS match_type text;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS competition text;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS note text;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS home_score integer;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS away_score integer;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS kickoff_time time;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS venue text;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS manual_override boolean NOT NULL DEFAULT false;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS source_club_id integer;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS source_season_id integer;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS source_game_id integer;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS first_scraped_at timestamptz;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS last_scraped_at timestamptz;
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fixtures_source_check') THEN
        ALTER TABLE fixtures ADD CONSTRAINT fixtures_source_check CHECK (source IN ('sanity', 'scraper'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fixtures_status_check') THEN
        ALTER TABLE fixtures ADD CONSTRAINT fixtures_status_check
            CHECK (status IN ('played', 'upcoming', 'cancelled', 'forfeit_us', 'forfeit_them'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fixtures_match_type_check') THEN
        ALTER TABLE fixtures ADD CONSTRAINT fixtures_match_type_check CHECK (match_type IN ('league', 'friendly'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fixtures_scraper_columns_check') THEN
        ALTER TABLE fixtures ADD CONSTRAINT fixtures_scraper_columns_check CHECK (
            source <> 'scraper' OR (home_team_id IS NOT NULL AND away_team_id IS NOT NULL AND status IS NOT NULL));
    END IF;
END $$;

