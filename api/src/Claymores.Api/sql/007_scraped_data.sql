CREATE TABLE IF NOT EXISTS standings (
    championship_id text PRIMARY KEY CHECK (championship_id ~ '^[0-9]+$'),
    season_label text NOT NULL CHECK (season_label ~ '^[0-9]{4}-[0-9]{4}$'),
    division_name text,
    source text NOT NULL CHECK (source IN ('standings-table', 'computed-from-schedule')),
    source_url text NOT NULL,
    last_updated timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS standings_season_idx ON standings (season_label, last_updated DESC);

CREATE TABLE IF NOT EXISTS standings_rows (
    championship_id text NOT NULL REFERENCES standings (championship_id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position > 0),
    team_name text NOT NULL,
    team_id bigint REFERENCES teams (id),
    pool text NOT NULL DEFAULT '',
    played integer NOT NULL,
    won integer NOT NULL,
    lost integer NOT NULL,
    drawn integer NOT NULL,
    points_for integer NOT NULL,
    points_against integer NOT NULL,
    points_difference integer NOT NULL,
    bonus_points integer NOT NULL,
    total_points integer NOT NULL,
    PRIMARY KEY (championship_id, position)
);

CREATE TABLE IF NOT EXISTS standings_playoffs (
    championship_id text NOT NULL REFERENCES standings (championship_id) ON DELETE CASCADE,
    ordinal integer NOT NULL,
    round text NOT NULL CHECK (round IN ('quarter', 'semi', 'third', 'final')),
    label text NOT NULL,
    match_date date,
    home_team text NOT NULL,
    away_team text NOT NULL,
    home_team_id bigint REFERENCES teams (id),
    away_team_id bigint REFERENCES teams (id),
    home_score integer,
    away_score integer,
    PRIMARY KEY (championship_id, ordinal)
);

-- ── Scrape log ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS scrape_runs (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('fixtures', 'standings')),
    trigger text NOT NULL CHECK (trigger IN ('cli', 'http')),
    parameters jsonb NOT NULL DEFAULT '{}'::jsonb,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    status text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'success', 'partial', 'failed', 'skipped')),
    summary jsonb,
    error text
);
CREATE INDEX IF NOT EXISTS scrape_runs_kind_started_idx ON scrape_runs (kind, started_at DESC);
